<?php

namespace App\Libraries;

use Sentry\SentrySdk;
use Sentry\Tracing\Span;
use Sentry\Tracing\SpanContext;
use Sentry\Tracing\Transaction;
use Sentry\Tracing\TransactionContext;

/**
 * Sentry Agent Tracing & Conversations Helper.
 *
 * Implements Sentry and OpenTelemetry GenAI Semantic Conventions:
 * - https://docs.sentry.io/product/agents/conversations/
 * - https://github.com/getsentry/sentry-conventions/
 */
class AgentTracing
{
    /**
     * Start an Agent Tracing transaction.
     *
     * @param string      $conversationId Stable opaque identifier for the conversation (e.g. conv_uuid)
     * @param string      $agentName      Descriptive agent name (e.g. ResortAdvisorAgent)
     * @param string|null $taskName       Optional name of the agent invocation task
     */
    public static function startAgentTransaction(
        string $conversationId,
        string $agentName,
        ?string $taskName = null
    ): ?Transaction {
        if (function_exists('initSentry')) {
            initSentry();
        }

        if (! class_exists('\\Sentry\\ClientBuilder')) {
            return null;
        }

        $hub = SentrySdk::getCurrentHub();
        if (! $hub->getClient()) {
            return null;
        }

        $txContext = new TransactionContext();
        $txContext->setName($taskName ?: "Agent Invocation: {$agentName}");
        $txContext->setOp('gen_ai.invoke_agent');
        $txContext->setData([
            'gen_ai.conversation.id' => $conversationId,
            'gen_ai.agent.name'        => $agentName,
        ]);

        $transaction = \Sentry\startTransaction($txContext);
        $hub->setSpan($transaction);

        return $transaction;
    }

    /**
     * Record a chat interaction turn within an agent execution.
     *
     * @param Span   $parentSpan      Parent transaction or span
     * @param string $conversationId  Conversation ID
     * @param string $agentName       Agent name
     * @param string $userPrompt      Prompt provided by user
     * @param string $assistantReply  Response generated by the agent/model
     * @param array  $metadata        Additional attributes (model, provider, tokens)
     */
    public static function recordChatTurn(
        Span $parentSpan,
        string $conversationId,
        string $agentName,
        string $userPrompt,
        string $assistantReply,
        array $metadata = []
    ): Span {
        $provider     = $metadata['provider'] ?? 'google';
        $model        = $metadata['model'] ?? 'gemini-1.5-pro';
        $inputTokens  = $metadata['input_tokens'] ?? mb_strlen($userPrompt) / 4;
        $outputTokens = $metadata['output_tokens'] ?? mb_strlen($assistantReply) / 4;
        $totalTokens  = $metadata['total_tokens'] ?? ($inputTokens + $outputTokens);

        $spanContext = new SpanContext();
        $spanContext->setOp('gen_ai.chat');
        $spanContext->setDescription($metadata['description'] ?? "Chat turn: {$agentName}");
        $spanContext->setData([
            'gen_ai.conversation.id' => $conversationId,
            'gen_ai.agent.name'      => $agentName,
            'gen_ai.provider.name'   => $provider,
            'gen_ai.request.model'   => $model,
            'gen_ai.response.model'  => $model,
            'gen_ai.input.messages'  => [
                [
                    'role'  => 'user',
                    'parts' => [
                        ['type' => 'text', 'content' => $userPrompt],
                    ],
                ],
            ],
            'gen_ai.output.messages' => [
                [
                    'role'  => 'assistant',
                    'parts' => [
                        ['type' => 'text', 'content' => $assistantReply],
                    ],
                ],
            ],
            'gen_ai.usage.input_tokens'  => (int) $inputTokens,
            'gen_ai.usage.output_tokens' => (int) $outputTokens,
            'gen_ai.usage.total_tokens'  => (int) $totalTokens,
        ]);

        $span = $parentSpan->startChild($spanContext);
        SentrySdk::getCurrentHub()->setSpan($span);

        return $span;
    }

    /**
     * Record a tool execution span within an agent turn.
     *
     * @param Span   $parentSpan     Parent chat or agent span
     * @param string $conversationId Conversation ID
     * @param string $toolName       Name of the tool executed
     * @param array  $input          Tool arguments
     * @param array  $output         Tool result
     */
    public static function recordToolExecution(
        Span $parentSpan,
        string $conversationId,
        string $toolName,
        array $input,
        array $output
    ): Span {
        $spanContext = new SpanContext();
        $spanContext->setOp('gen_ai.execute_tool');
        $spanContext->setDescription("Execute Tool: {$toolName}");
        $spanContext->setData([
            'gen_ai.conversation.id' => $conversationId,
            'gen_ai.tool.name'       => $toolName,
            'gen_ai.tool.input'      => json_encode($input),
            'gen_ai.tool.output'     => json_encode($output),
        ]);

        $span = $parentSpan->startChild($spanContext);
        SentrySdk::getCurrentHub()->setSpan($span);

        return $span;
    }

    /**
     * Finish an agent transaction and ensure traces are flushed.
     */
    public static function finishAgentTransaction(Transaction $transaction): void
    {
        $transaction->finish();

        $client = SentrySdk::getCurrentHub()->getClient();
        if ($client !== null) {
            $client->flush();
        }
    }
}
